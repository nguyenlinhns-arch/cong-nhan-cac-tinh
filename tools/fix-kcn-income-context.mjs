import "./rewrite-kcn-comparison.mjs";
import fs from "node:fs";
import path from "node:path";

const target = path.resolve("tuyen-tho-mo/chon-kcn-hay-lam-mo/index.html");
let html = fs.readFileSync(target, "utf8");
const canonicalIncome = "20–25 triệu đồng/tháng khi hoàn thành định mức lao động";
let changed = 0;

const exactReplacements = [
  [
    "Nghề mỏ không dành cho người chỉ nhìn thấy mức 20–25 triệu đồng",
    `Nghề mỏ không dành cho người chỉ nhìn thấy mức ${canonicalIncome}`,
  ],
  [
    "Nghề mỏ có Thu nhập 20–25 triệu đồng/tháng khi hoàn thành định mức lao động. không?",
    `Nghề mỏ có thu nhập ${canonicalIncome} không?`,
  ],
];
for (const [before, after] of exactReplacements) {
  if (html.includes(before)) {
    html = html.replaceAll(before, after);
    changed += 1;
  }
}

// Any visible text node that mentions the current 20–25 million range must
// carry the labor-norm condition. This catches copy regenerated by the KCN
// comparison renderer without coupling the repair to individual sentences.
html = html.replace(/>([^<>]*20[–-]25\s*triệu[^<>]*)</giu, (full, nodeText) => {
  if (/hoàn thành định mức lao động/iu.test(nodeText)) return full;
  let normalized = nodeText
    .replace(/20[–-]25\s*triệu\s*đồng\s*\/\s*tháng/giu, canonicalIncome)
    .replace(/20[–-]25\s*triệu\s*đồng(?!\s*\/\s*tháng)/giu, canonicalIncome)
    .replace(/20[–-]25\s*triệu(?!\s*đồng)/giu, canonicalIncome);
  if (!/hoàn thành định mức lao động/iu.test(normalized)) {
    normalized = `${normalized.replace(/[.\s]+$/u, "")} khi hoàn thành định mức lao động.`;
  }
  if (normalized !== nodeText) changed += 1;
  return `>${normalized}<`;
});

// Collapse any condition duplicated by legacy transforms and repair punctuation.
html = html
  .replace(/(khi hoàn thành định mức lao động)(?:[\s.,;:]+khi hoàn thành định mức lao động)+/giu, "$1")
  .replace(/định mức lao động\.\s+không\?/giu, "định mức lao động không?")
  .replace(/định mức lao động\.\s*\./giu, "định mức lao động.");

for (const forbidden of [
  ">Nghề mỏ không dành cho người chỉ nhìn thấy mức 20–25 triệu đồng<",
  ">Nghề mỏ có Thu nhập 20–25 triệu đồng/tháng khi hoàn thành định mức lao động. không?<",
]) {
  if (html.includes(forbidden)) throw new Error(`Incomplete income context remains: ${forbidden}`);
}

const incomeNodes = [...html.matchAll(/>([^<>]*20[–-]25\s*triệu[^<>]*)</giu)]
  .map(match => match[1].replace(/\s+/g, " ").trim());
const invalidIncomeNodes = incomeNodes.filter(text => !/hoàn thành định mức lao động/iu.test(text));
if (invalidIncomeNodes.length) {
  throw new Error(`KCN page has income text without labor-norm condition: ${invalidIncomeNodes.join(" | ")}`);
}

fs.writeFileSync(target, html);
console.log(JSON.stringify({
  status: "income-context-fixed",
  page: "/chon-kcn-hay-lam-mo/",
  canonicalIncome,
  replacementsApplied: changed,
  income_nodes: incomeNodes.length,
  invalid_income_nodes: invalidIncomeNodes.length,
}, null, 2));
