function clean(value) {
  return String(value || "").replace(/\s+/g, " ").trim();
}

export function applyEditorialSourceOverridesV5b(article = {}) {
  const override = overrides[article.slug];
  if (!override) return article;
  return {
    ...article,
    ...override,
    lead: clean(override.lead || article.lead),
    intro: (override.intro || article.intro || []).map(clean).filter(Boolean),
    editorialStandard: "journalism-expertise-communications-v5b",
    editorialV5: true,
  };
}

